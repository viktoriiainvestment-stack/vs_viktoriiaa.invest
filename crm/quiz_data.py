def card_matches(card, answers):
    """Чи підходить ця картка під відповіді клієнта.

    Підходить, тільки якщо відповідь на КОЖНЕ питання зі списку
    card["criteria"] входить у дозволені для нього значення. Питання,
    яких немає в "criteria" картки, не обмежують її.
    """
    return all(answers.get(key) in allowed for key, allowed in card["criteria"].items())


