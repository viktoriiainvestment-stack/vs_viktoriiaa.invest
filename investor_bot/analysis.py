"""Промпти й виклики Claude: швидка реакція на новий матеріал, зведений
аналіз проекту, відповіді на питання інвестора з посиланням на джерело.
"""
import claude_client
from retrieval import top_chunks

ANALYST_PERSONA = (
    "Ти — досвідчений аналітик інвестицій у нерухомість, який працює на "
    "приватного інвестора. Тобі надсилають матеріали від забудовників і "
    "менеджерів проектів (сайти, презентації, фінансові моделі, договори, "
    "фото/рендери), а ти оцінюєш їх тверезо й без прикрас: де сильні "
    "сторони, де ризики й нестиковки, чого бракує для рішення. Пишеш "
    "українською, конкретно, без води й без зайвого захвату."
)


def quick_take(project_name, title, text):
    system = (
        ANALYST_PERSONA
        + "\n\nЩойно надійшов один новий матеріал по проекту. Дай коротку "
        "(3-5 речень) першу реакцію: що це за документ, які ключові факти/цифри "
        "в ньому є, і чи є щось, що одразу впадає в око (плюс або red flag). "
        "Не вигадуй цифр, яких немає в тексті."
    )
    user = f"Проект: {project_name}\nМатеріал: {title}\n\nТекст:\n{text[:12000]}"
    return claude_client.ask(system, user, max_tokens=500)


def full_report(project_name, materials_with_text):
    """materials_with_text: list of {"title": str, "kind": str, "text": str}"""
    system = (
        ANALYST_PERSONA
        + "\n\nНа основі ВСІХ наданих матеріалів по проекту склади структурований "
        "інвестиційний аналіз українською за розділами:\n"
        "1. Про проект (що це, де, забудовник)\n"
        "2. Ключові фінансові показники (ціна входу, дохідність/орендні ставки, "
        "терміни, якщо є в матеріалах)\n"
        "3. Сильні сторони\n"
        "4. Ризики та нестиковки (в т.ч. якщо документи суперечать одне одному)\n"
        "5. Чого не вистачає для остаточного рішення — які документи/цифри "
        "варто запросити додатково\n"
        "6. Загальний висновок (одне-два речення)\n\n"
        "Де наводиш конкретну цифру чи факт — вказуй у дужках, з якого "
        "матеріалу вона взята. Не вигадуй нічого, чого немає в матеріалах."
    )
    blocks = []
    for m in materials_with_text:
        blocks.append(f"--- Матеріал: {m['title']} ({m['kind']}) ---\n{m['text'][:8000]}")
    user = f"Проект: {project_name}\n\n" + "\n\n".join(blocks)
    return claude_client.ask(system, user, max_tokens=2500)


def answer_question(project_name, question, chunks):
    """chunks: список фрагментів (з db.list_chunks) — уже відфільтрований
    top_chunks. Повертає текст відповіді з посиланням на джерело."""
    if not chunks:
        return (
            "У матеріалах цього проекту я поки нічого не знайшов по цьому "
            "питанню — можливо, потрібний документ ще не надіслано."
        )
    system = (
        ANALYST_PERSONA
        + "\n\nІнвестор ставить конкретне питання по проекту. Відповідай "
        "ТІЛЬКИ на основі наданих нижче фрагментів матеріалів — якщо "
        "відповіді в них немає, чесно скажи, що в наданих матеріалах цього "
        "немає, і не вигадуй. У кінці відповіді обов'язково вкажи джерело "
        "у форматі «Джерело: <назва матеріалу>, <місце>» для кожного факту, "
        "який використав."
    )
    context = "\n\n".join(
        f"[Матеріал: {c['material_title']}, {c['location']}]\n{c['text']}" for c in chunks
    )
    user = f"Проект: {project_name}\n\nПитання інвестора: {question}\n\nМатеріали:\n{context}"
    return claude_client.ask(system, user, max_tokens=1200)


def select_relevant(project_id, question, db_module, k=25):
    chunks = db_module.list_chunks(project_id)
    return top_chunks(question, chunks, k=k)


def select_relevant_for_chat(chat_id, question, db_module, k=40):
    chunks = db_module.list_chunks_for_chat(chat_id)
    return top_chunks(question, chunks, k=k, max_chars=55000)


def answer_cross_project(question, projects, chunks):
    """Питання одразу по ВСІХ збережених проектах інвестора (порівняння,
    вибір найкращого, оцінка ризику по регіону тощо) — а не по одному
    активному проекту."""
    reports = [p for p in projects if p.get("last_report")]
    if not chunks and not reports:
        return (
            "У базі ще немає жодного проаналізованого проекту — спершу "
            "додайте матеріали через /project і /analyze."
        )
    system = (
        ANALYST_PERSONA
        + "\n\nІнвестор ставить питання одразу по ВСІХ своїх збережених "
        "проектах (порівняння між ними, вибір найкращого, оцінка ризику по "
        "регіону тощо). Нижче — зведені аналізи проектів (якщо вже робились) "
        "і фрагменти оригінальних матеріалів. У відповіді чітко розділяй:\n"
        "1) Факти й цифри з конкретних проектів — з посиланням «Проект: "
        "<назва>, Джерело: <документ>, <місце>».\n"
        "2) Загальні міркування, яких немає в документах інвестора "
        "(наприклад, загальна ситуація з безпекою в регіоні) — познач їх "
        "окремо як «Загальний контекст (не з ваших матеріалів)» і подавай як "
        "орієнтовну думку, а не факт із документів.\n"
        "Не приписуй загальні знання проектним документам і навпаки."
    )
    blocks = []
    for p in reports:
        blocks.append(f"=== Проект «{p['name']}» — попередній зведений аналіз ===\n{p['last_report'][:4000]}")
    for c in chunks:
        blocks.append(f"[Проект: {c['project_name']}, Матеріал: {c['material_title']}, {c['location']}]\n{c['text']}")
    user = f"Питання інвестора (по всіх проектах разом): {question}\n\n" + "\n\n".join(blocks)
    return claude_client.ask(system, user, max_tokens=1600)
